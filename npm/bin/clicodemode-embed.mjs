#!/usr/bin/env node
// Bake a folder of .js/.json modules into one generated ES module at build
// time, so nothing is read from disk when the CLI runs:
//
//   npx clicodemode-embed js src/modules.generated.js
//
//   import modules from "./modules.generated.js";
//   cm.registerModules("mycli", modules);
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const [dir, out] = process.argv.slice(2);
if (!dir || !out) {
  console.error("usage: clicodemode-embed <modules-dir> <out.js>");
  process.exit(2);
}
const files = {};
const walk = (d) => {
  for (const e of readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = join(d, e.name);
    if (e.isDirectory()) walk(full);
    else if (/\.(js|json)$/.test(e.name)) files[relative(dir, full).split(sep).join("/")] = readFileSync(full, "utf8");
  }
};
walk(dir);
if (Object.keys(files).length === 0) {
  console.error(`clicodemode-embed: no .js or .json files under ${dir}`);
  process.exit(1);
}
writeFileSync(out, `// Generated by clicodemode-embed from ${dir}. Do not edit.\nexport default ${JSON.stringify(files, null, 2)};\n`);
console.error(`clicodemode-embed: ${Object.keys(files).length} module(s) -> ${out}`);
